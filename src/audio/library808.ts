export interface TriggeredVoice {
  source: AudioBufferSourceNode;
  gain: GainNode;
}

export function midiToHz(midi: number): number {
  return 440 * Math.pow(2, (midi - 69) / 12);
}

/**
 * Plays a real decoded 808 AudioBuffer (from WAV file or phone import),
 * pitched accurately to midiNote with optional sequencer slide.
 * Returns { source, gain } so the engine can enforce monophonic Cut-Itself.
 */
export function trigger808Sound(
  ctx: BaseAudioContext,
  dest: AudioNode,
  sample: Sample808,
  sampleBuffer: AudioBuffer | null,
  time: number,
  midiNote = 36,
  velocity = 0.9,
  slide = false,
  slideTargetMidi?: number
): TriggeredVoice | null {
  // Imported projects and custom sample metadata are untrusted runtime data.
  // Reject unusable buffers/timestamps instead of scheduling NaN/Infinity into WebAudio.
  if (!sample?.available || !sampleBuffer ||
      !Number.isFinite(sampleBuffer.duration) || sampleBuffer.duration <= 0 ||
      !Number.isFinite(time)) {
    return null;
  }

  const startAt = Math.max(0, time, ctx.currentTime + 0.002);
  const safeMidi = Number.isFinite(midiNote)
    ? Math.max(0, Math.min(127, midiNote))
    : 36;
  const safeRoot = Number.isFinite(sample.rootNote)
    ? Math.max(0, Math.min(127, sample.rootNote))
    : 36;
  // Keep pitch shifting within a practical two-octave range in either direction.
  const rawRate = Math.pow(2, (safeMidi - safeRoot) / 12);
  const baseRate = Math.max(0.25, Math.min(4, rawRate));
  const vel = Number.isFinite(velocity)
    ? Math.max(0.1, Math.min(1, velocity))
    : 0.85;
  const playDur = Math.max(0.006, Math.min(sampleBuffer.duration / baseRate, 2.5));
  const peakGain = vel * 0.82;

  const src = ctx.createBufferSource();
  src.buffer = sampleBuffer;
  src.playbackRate.setValueAtTime(baseRate, startAt);

  if (slide) {
    const requestedGlide = Number.isFinite(sample.glideMs) ? sample.glideMs : 80;
    const glideMs = Math.max(5, Math.min(500, requestedGlide));
    const glideEnd = startAt + Math.max(0.006, glideMs / 1000);
    // Glide toward the next sequenced MIDI note when supplied. Older projects
    // without a target retain a subtle upward fifth as a backwards-compatible fallback.
    const targetMidi = Number.isFinite(slideTargetMidi)
      ? Math.max(0, Math.min(127, Number(slideTargetMidi)))
      : safeMidi + 7;
    const targetRateRaw = Math.pow(2, (targetMidi - safeRoot) / 12);
    const glideTarget = Math.max(0.25, Math.min(4, targetRateRaw));
    src.playbackRate.exponentialRampToValueAtTime(glideTarget, glideEnd);
  }

  const gain = ctx.createGain();
  const attack = Math.min(0.003, playDur * 0.2);
  const release = Math.min(0.035, playDur * 0.35);
  const sustainStart = startAt + attack;
  const sustainEnd = Math.max(sustainStart, startAt + playDur - release);
  const endAt = Math.max(sustainEnd + 0.001, startAt + playDur);

  gain.gain.setValueAtTime(0.0001, startAt);
  gain.gain.linearRampToValueAtTime(peakGain, sustainStart);
  gain.gain.setValueAtTime(peakGain, sustainEnd);
  gain.gain.exponentialRampToValueAtTime(0.0001, endAt);

  src.connect(gain);
  gain.connect(dest);
  src.start(startAt);
  src.stop(endAt + 0.02);
  return { source: src, gain };
}

/**
 * Plays a studio-rendered WAV kit sample (Kick, Snare, Clap, HiHat, OpenHat, Perc, Bell).
 * bell_trap_pro.wav is centered at C5 (MIDI 72) so C4..D5 melodies never pitch-chirp.
 */
export function triggerKitSample(
  ctx: BaseAudioContext,
  dest: AudioNode,
  trackId: Exclude<BeatTrackId, '808'>,
  buffer: AudioBuffer | undefined,
  time: number,
  velocity = 0.85,
  midiNote = 60
): TriggeredVoice | null {
  if (!buffer || !Number.isFinite(buffer.duration) || buffer.duration <= 0 || !Number.isFinite(time)) {
    return null;
  }

  const startAt = Math.max(0, time, ctx.currentTime + 0.002);
  const vel = Number.isFinite(velocity)
    ? Math.max(0.08, Math.min(1, velocity))
    : 0.85;
  const safeMidi = Number.isFinite(midiNote)
    ? Math.max(0, Math.min(127, midiNote))
    : 72;
  const src = ctx.createBufferSource();
  src.buffer = buffer;

  let rate = 1;
  if (trackId === 'melody') {
    rate = Math.pow(2, (safeMidi - 72) / 12);
  }
  // Keep custom/imported MIDI values from producing unusable playback rates.
  rate = Math.max(0.25, Math.min(4, rate));
  src.playbackRate.setValueAtTime(rate, startAt);

  const trackGainScale: Record<Exclude<BeatTrackId, '808'>, number> = {
    kick: 0.88,
    snare: 0.84,
    clap: 0.68,
    hihat: 0.52,
    openhat: 0.46,
    perc: 0.56,
    melody: 0.48,
  };

  const playDur = Math.max(0.006, Math.min(buffer.duration / rate, trackId === 'melody' ? 1.45 : 1.0));
  const gain = ctx.createGain();
  const targetGain = vel * trackGainScale[trackId];
  const attack = Math.min(0.002, playDur * 0.2);
  const fadeOut = Math.min(trackId === 'melody' ? 0.06 : 0.015, playDur * 0.35);
  const sustainEnd = Math.max(startAt + attack, startAt + playDur - fadeOut);
  const endAt = Math.max(startAt + playDur, sustainEnd + 0.001);
  gain.gain.setValueAtTime(0.0001, startAt);
  gain.gain.linearRampToValueAtTime(targetGain, startAt + attack);
  gain.gain.setValueAtTime(targetGain, sustainEnd);
  gain.gain.exponentialRampToValueAtTime(0.0001, endAt);

  src.connect(gain);
  gain.connect(dest);
  src.start(startAt);
  src.stop(endAt + 0.02);
  return { source: src, gain };
}
